import { loadTranscriptFile } from '../src/indexer/index.ts';
import { seedRules } from '../src/gates/rules.ts';
import { FakeDrafter } from '../src/gates/draft.ts';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { openDb, migrate, getPr } from '../src/db/db.ts';
import { loadConfig } from '../src/config.ts';
import { clientForIdentity } from '../src/primitive/registry.ts';
import { listLocalInbox, submitLocalReply } from '../src/primitive/local.ts';
import { requestContext } from '../src/mcp/tools.ts';
import { initializeCursor } from '../src/pipeline/worker.ts';
import { sendQueuedRequests, pollDeliveries } from '../src/pipeline/requester.ts';
import { pollInbound, processReceived, pollApprovals } from '../src/pipeline/responder.ts';
test('persistent local transport waits for an explicit human reply then delivers exact edit', async () => {
    const db = openDb(':memory:');
    migrate(db);
    const config = loadConfig({});
    loadTranscriptFile(db, config.RESPONDER_IDENTITY, new URL('../demo/fixtures/bob-session.jsonl', import.meta.url).pathname);
    seedRules(db, new URL('../demo/fixtures/rules.sql', import.meta.url).pathname, config.RESPONDER_IDENTITY);
    const deps = { config, drafter: new FakeDrafter(), clientFor: (identity: string) => clientForIdentity(identity, config, db) };
    await initializeCursor(db, deps);
    const id = requestContext(db, { responder: config.RESPONDER_IDENTITY, topic: 'acme-sdk/retries', question: 'Why do concurrent retries create duplicate charges with SDK 2.3?' }, { requesterIdentity: config.REQUESTER_IDENTITY }).structured.id;
    await sendQueuedRequests(db, deps);
    await pollInbound(db, deps);
    await processReceived(db, deps);
    await pollApprovals(db, deps);
    assert.equal(getPr(db, id)?.state, 'awaiting_approval');
    const replacement = '  \r\n> Keep one idempotency key across retries.\r\nUse one idempotencyKey outside the retry loop.  \r\n';
    const messages = listLocalInbox(db, config.APPROVER_EMAIL);
    assert.equal(messages.length, 1);
    submitLocalReply(db, { sentEmailId: messages[0].sentEmailId, author: config.APPROVER_EMAIL, bodyText: 'edit\n' + replacement });
    await pollApprovals(db, deps);
    assert.equal(getPr(db, id)?.state, 'approved');
    await pollDeliveries(db, deps);
    assert.equal(getPr(db, id)?.state, 'delivered');
    assert.equal(getPr(db, id)?.approved_text, replacement);
    db.close();
});
